import assert from 'node:assert/strict';
import * as E from './dist/engine.js';
import {NPC_EVENTS,beginNpcEvent,npcEventDefinition} from './dist/npc-events.js';
import {renderNpcEventBoard,renderNpcAreaObjectives} from './dist/npc-event-ui.js';
import {renderStoryEventBoard} from './dist/story-event-ui.js';
import {buildRegionSnapshot,travelBlockReason,buildRegionModel,renderRegion} from './dist/adjacent-region.js';
import {renderPlannedRoute} from './dist/dwarf-region-ui.js';
import {idleActionPreview} from './dist/idle-action-ui.js';
const now=Date.now();
const fixture=(race='human')=>{const s=E.fresh(race);E.normalizeHealth(s,now);E.normalizeExpedition(s);return s;};
const button=(html,attrs)=>html.match(new RegExp('<button[^>]*'+attrs+'[^>]*>'))?.[0];
const busy=s=>{s.running=true;s.activeEncounter={done:false};return s;};
const s=busy(fixture());
let raw=JSON.stringify(s);
assert.equal(idleActionPreview(s),s);assert.notEqual(idleActionPreview(s,true),s);
assert.equal(idleActionPreview({...s,running:false},true).activeEncounter,s.activeEncounter,'manual pause is not auto-resumable');
assert.equal(idleActionPreview({...s,activeEncounter:{storyScenario:{}}},true).running,true,'scenario stays authoritative');
const snap=buildRegionSnapshot(s,now,null,{coordinateIdle:true});
const node=snap.nodes.find(n=>n.id===s.siteId+'.field');
assert.equal(travelBlockReason(node,snap),'');
assert.match(travelBlockReason(node,{...snap,coordinateIdle:false}),/停止远征/);
for(const override of [{warLocked:true},{unlocked:false},{budgetReady:false},{readyAt:now+1}])assert(travelBlockReason({...node,...override},snap));
assert(travelBlockReason(node,{...snap,resting:true}));
assert.equal(buildRegionSnapshot({...s,running:false},now,null,{coordinateIdle:true}).coordinateIdle,false);
assert.equal(buildRegionSnapshot({...s,activeEncounter:{storyScenario:{}}},now,null,{coordinateIdle:true}).coordinateIdle,false);
const model=buildRegionModel(snap,{viewAreaId:s.siteId,previewNodeId:node.id});
const html=renderRegion(model);assert(!button(html,'data-region-action="arrive"').includes('disabled'));assert.match(html,/本场结束后自动执行/);
const route=renderPlannedRoute(snap.nodes,s,{encounter:s.activeEncounter,coordinateIdle:true,now});
assert(!button(route,'id="dungeonBtn"').includes('disabled'));
assert(button(renderPlannedRoute(snap.nodes,s,{encounter:s.activeEncounter,now}),'id="dungeonBtn"').includes('disabled'));
assert.equal(JSON.stringify(s),raw,'UI leaves live combat and state untouched');
const def=Object.values(NPC_EVENTS).find(d=>d.objectiveVersion===2&&d.areaId==='human.a01');
const task=busy(fixture());raw=JSON.stringify(task);
const opts={race:def.race,areaId:def.areaId,coordinateIdle:true,now};
assert(!button(renderNpcEventBoard(task,opts),'data-npc-action="accept" data-npc-event="'+def.id+'"').includes('disabled'));
assert(button(renderNpcEventBoard(task,{...opts,coordinateIdle:false}),'data-npc-action="accept" data-npc-event="'+def.id+'"').includes('disabled'));
assert(button(renderNpcEventBoard({...task,siteId:'goblin.a01'},opts),'data-npc-action="accept" data-npc-event="'+def.id+'"').includes('disabled'));
assert.equal(JSON.stringify(task),raw);
const investigate=Object.values(NPC_EVENTS).find(d=>d.objectiveVersion===2&&d.taskObjective?.kind==='investigate'&&d.areaId==='dwarf.a01');
assert(investigate);const inv=fixture('dwarf');assert(beginNpcEvent(inv,investigate.id,now));const point=npcEventDefinition(inv,investigate.id).objective.checkpoints[0];inv.siteId=point.areaId;busy(inv);raw=JSON.stringify(inv);
assert(!button(renderNpcAreaObjectives(inv,{areaId:point.areaId,coordinateIdle:true,now}),'data-npc-action="investigate"').includes('disabled'));
assert(button(renderNpcAreaObjectives({...inv,running:false},{areaId:point.areaId,coordinateIdle:true,now}),'data-npc-action="investigate"').includes('disabled'));
assert.equal(JSON.stringify(inv),raw);
const story=busy(fixture());story.siteId='goblin.a01';story.location=0;story.expedition.fieldId='goblin.a01.field';raw=JSON.stringify(story);
assert(!button(renderStoryEventBoard(story,{coordinateIdle:true}),'data-story-action="begin" data-story-scene="C01.H01.human"').includes('disabled'));
assert(button(renderStoryEventBoard(story),'data-story-action="begin" data-story-scene="C01.H01.human"').includes('disabled'));
assert.equal(JSON.stringify(story),raw);
console.log('PASS idle-action UI: opt-in queueable map/routes/NPC/story/investigation; paused/scenario, location, war, rest and unlock guards; render purity.');
